# ----------------------------------------------------------------------------
# 1. 轴线圆检测
# ----------------------------------------------------------------------------

@dataclass
class AxisCircle:
    """轴线交点圆。"""
    cx: float          # 中心 x（像素）
    cy: float          # 中心 y（像素）
    radius: float      # 半径（像素）
    side: str          # 'top' / 'bottom' / 'left' / 'right' / 'unknown'

    def to_mm(self, scale: float):
        """返回毫米坐标（已翻 y 轴向上）。"""
        return AxisCircleMm(self.cx * scale, -self.cy * scale, self.radius * scale, self.side)


@dataclass
class AxisCircleMm:
    cx_mm: float
    cy_mm: float
    radius_mm: float
    side: str


def detect_axis_circles(img: np.ndarray, y_bands: dict, x_bands: dict) -> List[AxisCircle]:
    """
    检测轴线交点圆。

    y_bands: {side: (y_min, y_max)}  e.g. {'top': (300, 360), 'bottom': (4040, 4100)}
    x_bands: {side: (x_min, x_max)}  e.g. {'left': (520, 620), 'right': (6950, 7150)}

    Returns: list of AxisCircle，按 side+位置排序
    """
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    _, binary = cv2.threshold(gray, 180, 255, cv2.THRESH_BINARY)
    n, labels, stats, centroids = cv2.connectedComponentsWithStats(binary, connectivity=8)

    result = []

    # 横轴圆：按 y_band 找
    for side, (y_min, y_max) in y_bands.items():
        for i in range(1, n):
            x, y, w, h, area = stats[i]
            if not (y_min < y < y_max):
                continue
            if not (50 < w < 75 and 50 < h < 75 and abs(w - h) < 6):
                continue
            mask = (labels == i).astype(np.uint8) * 255
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
            if not contours:
                continue
            perim = cv2.arcLength(contours[0], True)
            if perim < 1:
                continue
            circularity = 4 * math.pi * area / (perim * perim)
            fill = area / (w * h)
            if 0.7 < circularity < 0.95 and 0.55 < fill < 0.75:
                result.append(AxisCircle(
                    cx=centroids[i][0], cy=centroids[i][1],
                    radius=w / 2, side=side,
                ))

    # 纵轴圆：按 x_band 找
    for side, (x_min, x_max) in x_bands.items():
        for i in range(1, n):
            x, y, w, h, area = stats[i]
            if not (x_min < x < x_max):
                continue
            if not (50 < w < 75 and 50 < h < 75 and abs(w - h) < 6):
                continue
            mask = (labels == i).astype(np.uint8) * 255
            contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
            if not contours:
                continue
            perim = cv2.arcLength(contours[0], True)
            if perim < 1:
                continue
            circularity = 4 * math.pi * area / (perim * perim)
            fill = area / (w * h)
            if 0.7 < circularity < 0.95 and 0.55 < fill < 0.75:
                # 避免重复
                if not any(abs(c.cx - centroids[i][0]) < 5 and abs(c.cy - centroids[i][1]) < 5 for c in result):
                    result.append(AxisCircle(
                        cx=centroids[i][0], cy=centroids[i][1],
                        radius=w / 2, side=side,
                    ))

    return result


# ----------------------------------------------------------------------------
# 2. AutoLISP 脚本生成
# ----------------------------------------------------------------------------

LAYER_DEFS = [
    ("AXIS",     1,  "DASHDOT"),  # 红
    ("WALL",     7,  "Continuous"),  # 白/黑
    ("WALL_EXT", 5,  "Continuous"),  # 蓝 (外墙加粗)
    ("COLUMN",   8,  "Continuous"),
    ("OPENING",  3,  "Continuous"),
    ("DIM",      2,  "Continuous"),
    ("TEXT",     4,  "Continuous"),
    ("TITLE",    6,  "Continuous"),
]


def _lisp_header() -> str:
    return f"""
; Auto-generated by scan-to-dwg (cad_redraw mode)
; Timestamp: {__import__('datetime').datetime.now().isoformat()}
; 图层定义
(defun setup-layers ()
  {"".join(f'(if (not (tblsearch "LAYER" "{name}")) (entmake (list (cons 0 "LAYER") (cons 2 "{name}") (cons 70 0) (cons 62 {color}) (cons 6 "{ltype}"))))' for name, color, ltype in LAYER_DEFS)}
)
"""

def _lisp_axis_grid(h_axes: List[float], v_axes: List[float], axis_radius_mm: float) -> str:
    """绘制轴线网格。h_axes/v_axes 单位 mm。"""
    lines = []
    lines.append("(setup-layers)")
    lines.append('(setvar "CLAYER" "AXIS")')

    # 横向轴线
    for i, y in enumerate(v_axes):
        x_min = min(h_axes) - 200
        x_max = max(h_axes) + 200
        lines.append(f'(command "_.LINE" {x_min:.1f} {y:.1f} 0.0 {x_max:.1f} {y:.1f} 0.0 "")')

    # 纵向轴线
    for x in h_axes:
        y_min = min(v_axes) - 200
        y_max = max(v_axes) + 200
        lines.append(f'(command "_.LINE" {x:.1f} {y_min:.1f} 0.0 {x:.1f} {y_max:.1f} 0.0 "")')

    # 轴线圆（用 0 半径，标记交点）
    lines.append('(setvar "CLAYER" "AXIS")')
    for x in h_axes:
        for y in v_axes:
            lines.append(f'(command "_.CIRCLE" {x:.1f} {y:.1f} 0.0 {axis_radius_mm:.1f})')

    return "\n".join(lines)


def _lisp_axis_labels(h_axes: List[float], v_axes: List[float],
                      h_labels: List[str], v_labels: List[str],
                      label_offset: float = 250) -> str:
    """绘制轴线编号（圆外标注）。"""
    lines = []
    lines.append('(setvar "CLAYER" "TEXT")')
    height = label_offset / 3
    # 顶部横轴编号
    for x, label in zip(h_axes, h_labels):
        y = max(v_axes) + label_offset
        lines.append(f'(command "_.TEXT" {x:.1f} {y:.1f} 0.0 {height:.1f} 0.0 "{label}")')
    # 底部横轴编号
    for x, label in zip(h_axes, h_labels):
        y = min(v_axes) - label_offset
        lines.append(f'(command "_.TEXT" {x:.1f} {y:.1f} 0.0 {height:.1f} 0.0 "{label}")')
    # 左侧纵轴编号
    for y, label in zip(v_axes, v_labels):
        x = min(h_axes) - label_offset
        lines.append(f'(command "_.TEXT" {x:.1f} {y:.1f} 0.0 {height:.1f} 0.0 "{label}")')
    # 右侧纵轴编号
    for y, label in zip(v_axes, v_labels):
        x = max(h_axes) + label_offset
        lines.append(f'(command "_.TEXT" {x:.1f} {y:.1f} 0.0 {height:.1f} 0.0 "{label}")')

    return "\n".join(lines)


def _lisp_walls(walls: List[Tuple[List[Tuple[float, float]], bool]]) -> str:
    """
    绘制墙线。walls: [(polyline_points, is_external)]
    is_external=True 时用 WALL_EXT 层（加粗）。
    LISP 语法：_.PLINE 接收离散坐标点，"" 结束输入，"_C" 闭合。
    """
    lines = []
    for polyline, is_external in walls:
        layer = "WALL_EXT" if is_external else "WALL"
        lines.append(f'(setvar "CLAYER" "{layer}")')
        # 用 PLINE 命令，坐标直接传
        coords = " ".join(f"{x:.1f} {y:.1f}" for x, y in polyline)
        lines.append(f'(command "_.PLINE" {coords} "" "_C")')
    return "\n".join(lines)


def _lisp_footer() -> str:
    return """
; 缩放到全部对象
(command "_.ZOOM" "_E")
(princ)
"""


def generate_lisp(h_axes_mm: List[float], v_axes_mm: List[float],
                  h_labels: List[str], v_labels: List[str],
                  walls: List[Tuple[List[Tuple[float, float]], bool]] = None,
                  axis_radius_mm: float = 25) -> str:
    """组装完整 LISP 脚本。"""
    parts = [_lisp_header(),
             _lisp_axis_grid(h_axes_mm, v_axes_mm, axis_radius_mm),
             _lisp_axis_labels(h_axes_mm, v_axes_mm, h_labels, v_labels)]
    if walls:
        parts.append(_lisp_walls(walls))
    parts.append(_lisp_footer())
    return "\n\n".join(parts)



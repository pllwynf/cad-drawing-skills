# 3. accoreconsole 执行
# ----------------------------------------------------------------------------

def find_accoreconsole() -> Optional[str]:
    """查找 accoreconsole.exe。"""
    candidates = [
        r"D:\工作安装软件\cad\AutoCAD 2022\accoreconsole.exe",
        r"C:\Program Files\Autodesk\AutoCAD 2022\accoreconsole.exe",
        r"C:\Program Files\Autodesk\AutoCAD 2024\accoreconsole.exe",
    ]
    for c in candidates:
        if os.path.isfile(c):
            return c
    return None


def run_lisp(lisp_path: str, output_dwg: str, acad_path: str = None,
             template: str = "acadiso.dwt") -> Tuple[bool, str]:
    """
    用 accoreconsole 执行 LISP 脚本生成 DWG。

    accoreconsole 加载 LISP 的正确方式：
    1. 启动时 /b 指定 .scr 脚本
    2. .scr 中用 (load "path") 加载 LISP
    3. LISP 中的命令会自动执行
    4. 最后 SAVEAS 输出 DWG
    """
    if acad_path is None:
        acad_path = find_accoreconsole()
    if not acad_path:
        return False, "accoreconsole.exe not found"

    # 准备路径（用正斜杠）
    lisp_path_fwd = lisp_path.replace("\\", "/")
    output_dwg_fwd = output_dwg.replace("\\", "/")

    # .scr 脚本：启动时按顺序执行
    # 用 _NEWFILE 清理状态，然后 (load ...) 加载 LISP，然后 SAVEAS 保存
    scr_content = f"""_NEWFILE
(load "{lisp_path_fwd}")
(command "_SAVEAS" "" "{output_dwg_fwd}")
(command "_.QUIT")
"""
    scr_path = lisp_path.replace(".lsp", ".scr")
    with open(scr_path, "w", encoding="utf-8") as f:
        f.write(scr_content)

    # 切换到输出目录
    output_dir = os.path.dirname(output_dwg) or "."
    cmd = [
        acad_path,
        "/nologo",  # 不显示 logo
        "/s", scr_path,  # 加载脚本
        "/t", template,  # 模板
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600, cwd=output_dir)
        log = proc.stdout + "\n--- STDERR ---\n" + proc.stderr
        return os.path.isfile(output_dwg), log
    except subprocess.TimeoutExpired:
        return False, "Timeout after 600s"
    except Exception as e:
        return False, f"Error: {e}"


# ----------------------------------------------------------------------------
# 4. 主入口：从 PDF/PNG 到 DWG
# ----------------------------------------------------------------------------

def process_drawing(input_path: str, output_dir: str,
                    pdf_page: int = 0, render_dpi: int = 200,
                    h_labels: List[str] = None, v_labels: List[str] = None) -> dict:
    """
    主处理流程：
    1. 加载图片（PDF 渲染 或 直接读图）
    2. 检测轴线圆
    3. 计算比例（px → mm）
    4. 生成 LISP
    5. 用 accoreconsole 执行
    6. 返回结果
    """
    os.makedirs(output_dir, exist_ok=True)
    stem = Path(input_path).stem

    # 1) 加载图像
    if input_path.lower().endswith(".pdf"):
        import fitz
        doc = fitz.open(input_path)
        page = doc[pdf_page]
        pix = page.get_pixmap(dpi=render_dpi)
        img_path = os.path.join(output_dir, f"{stem}_p{pdf_page+1}.png")
        pix.save(img_path)
        img = cv2.imread(img_path)
        page_w_mm = page.rect.width * 25.4 / 72
        page_h_mm = page.rect.height * 25.4 / 72
    else:
        img = cv2.imread(input_path)
        img_path = input_path
        # 假设 200 DPI, 1:100 比例 → mm = px / (200/25.4) = px / 7.874
        # 或者用图像尺寸 / 标准 A1 (594x841 mm) 估算
        page_w_mm = img.shape[1] * 25.4 / render_dpi
        page_h_mm = img.shape[0] * 25.4 / render_dpi

    h_px, w_px = img.shape[:2]
    scale_x = page_w_mm / w_px  # mm/px
    scale_y = page_h_mm / h_px
    avg_scale = (scale_x + scale_y) / 2

    # 2) 检测轴线
    # 自适应 y_band：根据图像比例推断
    # 顶部横轴在 y = h_px * 0.07 左右
    # 底部横轴在 y = h_px * 0.86 左右
    y_top = int(h_px * 0.06)
    y_bot = int(h_px * 0.87)
    x_left = int(w_px * 0.05)
    x_right = int(w_px * 0.70)  # 右侧墙身大样在 0.7-0.9
    y_bands = {
        "top": (y_top - 30, y_top + 30),
        "bottom": (y_bot - 30, y_bot + 30),
    }
    x_bands = {
        "left": (x_left - 50, x_left + 50),
        "right_main": (x_right - 50, x_right + 50),
    }

    circles = detect_axis_circles(img, y_bands, x_bands)

    # 3) 分组：top/bottom 合并去重 → 横向轴线
    h_axis_px = sorted(set([
        round(c.cx) for c in circles
        if c.side in ("top", "bottom")
    ]))
    # left/right 合并 → 纵向轴线
    v_axis_px = sorted(set([
        round(c.cy) for c in circles
        if c.side in ("left", "right_main")
    ]))

    # 4) 转换到 mm，翻 y 轴
    # 图像 y 向下，CAD y 向上 → 以图像底边为 0
    h_axes_mm = [x * scale_x for x in h_axis_px]
    v_axes_mm = [(h_px - y) * scale_y for y in v_axis_px]  # 翻转

    # 标准化：平移使 (0,0) 在最左下轴线交点
    x_offset = min(h_axes_mm)
    y_offset = min(v_axes_mm)
    h_axes_mm = [x - x_offset for x in h_axes_mm]
    v_axes_mm = [y - y_offset for y in v_axes_mm]

    # 5) 标签
    if h_labels is None:
        h_labels = [f"AXIS-{i+1}" for i in range(len(h_axes_mm))]
    if v_labels is None:
        v_labels = [f"AXIS-{chr(65+i)}" for i in range(len(v_axes_mm))]

    # 6) 生成 LISP
    lisp_content = generate_lisp(h_axes_mm, v_axes_mm, h_labels, v_labels)
    lisp_path = os.path.join(output_dir, f"{stem}_redraw.lsp")
    with open(lisp_path, "w", encoding="utf-8") as f:
        f.write(lisp_content)

    # 7) 元数据 JSON
    meta = {
        "source": input_path,
        "image": img_path,
        "image_size_px": [w_px, h_px],
        "page_size_mm": [page_w_mm, page_h_mm],
        "scale_mm_per_px": [scale_x, scale_y],
        "h_axes_count": len(h_axes_mm),
        "v_axes_count": len(v_axes_mm),
        "h_axes_mm": h_axes_mm,
        "v_axes_mm": v_axes_mm,
        "h_labels": h_labels,
        "v_labels": v_labels,
    }
    meta_path = os.path.join(output_dir, f"{stem}_redraw.json")
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)

    # 8) 执行 LISP
    dwg_path = os.path.join(output_dir, f"{stem}_redraw.dwg")
    success, log = run_lisp(lisp_path, dwg_path)

    return {
        "lisp": lisp_path,
        "dwg": dwg_path if success else None,
        "meta": meta_path,
        "log": log,
        "success": success,
        "axis_count": {"h": len(h_axes_mm), "v": len(v_axes_mm)},
    }


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("input", help="PDF or PNG file")
    ap.add_argument("--output", "-o", default="output", help="Output directory")
    ap.add_argument("--page", type=int, default=0)
    ap.add_argument("--dpi", type=int, default=200)
    args = ap.parse_args()

    result = process_drawing(args.input, args.output, args.page, args.dpi)
    print(json.dumps({k: v for k, v in result.items() if k != "log"}, ensure_ascii=False, indent=2))
    if not result["success"]:
        print("\n--- LISP execution log ---")
        print(result["log"])

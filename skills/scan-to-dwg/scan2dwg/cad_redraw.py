"""
scan2dwg.cad_redraw
-------------------
"读图 → 重绘" 模式：解析扫描图 → 生成 AutoLISP → accoreconsole 执行 → 干净 DWG。

与 v1 (纯矢量化) 完全不同：
- 检测轴线圆（位置精确）
- 解析关键尺寸 (axis 间距)
- 在 AutoCAD 里按真实坐标绘制轴线网格 + 主轮廓
- 图层结构清晰：AXIS / WALL / DIM / TEXT
- 不会产生碎线

依赖：opencv-python, pytesseract（可选 OCR）, ezdxf
输出：.lsp + .dwg
"""
